def ui_language(language: str | None = None) -> str:
    """Resolve DE/EN from TM_LANG; keep German as the UI default."""
    value = language if language is not None else os.environ.get("TM_LANG", "de")
    code = value.strip().replace("_", "-").split("-", 1)[0].lower()
    return code if code in _TEXT else "de"


def translate(language: str | None, key: str, **values: object) -> str:
    """Return one interface string; event data and identifiers stay untouched."""
    value = _TEXT[ui_language(language)][key]
    return value.format(**values) if values else value
